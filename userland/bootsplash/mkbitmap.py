#!/usr/bin/env python3
# logo.h from lfetch's logo.lisp: the braille rows as a dot bitmap.
import re, sys
src = open(sys.argv[1] if len(sys.argv) > 1 else '../lfetch/src/logo.lisp', encoding='utf-8').read()
block = src[src.index('*lambda-rows*'):]; block = block[:block.index('))') + 1]
rows = re.findall(r'"([^"]*)"', block)
pos = {0: (0, 0), 1: (0, 1), 2: (0, 2), 3: (1, 0), 4: (1, 1), 5: (1, 2), 6: (0, 3), 7: (1, 3)}
W = max(len(r) for r in rows) * 2; H = len(rows) * 4
bm = [[0] * W for _ in range(H)]
for ri, r in enumerate(rows):
    for ci, ch in enumerate(r):
        if ch != ' ':
            bits = ord(ch) - 0x2800
            for b, (x, y) in pos.items():
                if bits >> b & 1: bm[ri * 4 + y][ci * 2 + x] = 1
out = ["/* The LispBSD lambda from lfetch's logo.lisp, %dx%d dots; generated by mkbitmap.py. */" % (W, H),
       "#define LOGO_W %d" % W, "#define LOGO_H %d" % H, "static const unsigned char logo_bits[LOGO_H][LOGO_W] = {"]
out += ["\t{" + ",".join(str(v) for v in row) + "}," for row in bm] + ["};"]
open('logo.h', 'w').write("\n".join(out) + "\n")
