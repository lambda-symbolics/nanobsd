#!/usr/bin/env python3
# font.h: ASCII 32..126 of ProFontExtended as a bitmap font for bootsplash.
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/ProFontExtended .ttf'
size = int(sys.argv[2]) if len(sys.argv) > 2 else 12
f = ImageFont.truetype(path, size)
# cell from the widest glyph and the font's ascent+descent
asc, desc = f.getmetrics()
W = max(int(f.getlength(chr(c))) for c in range(32, 127)); H = asc + desc
rows = []
for c in range(32, 127):
    im = Image.new('1', (W, H), 0); ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=1)
    rows.append([sum(1 << x for x in range(W) if im.getpixel((x, y))) for y in range(H)])
out = ["/* ProFontExtended %dpx, ASCII 32..126, %dx%d cells, bit x set = pixel; generated by mkfont.py. */" % (size, W, H),
       "#define FONT_W %d" % W, "#define FONT_H %d" % H, "static const unsigned short font_bits[95][FONT_H] = {"]
out += ["\t{" + ",".join("0x%x" % v for v in r) + "}, /* '%s' */" % (chr(32 + i).replace('\\', '\\\\').replace("'", "\\'").replace('*/', '* /')) for i, r in enumerate(rows)] + ["};"]
open('font.h', 'w').write("\n".join(out) + "\n"); print("font", W, "x", H)
im = Image.new('1', (W * 12, H), 0); ImageDraw.Draw(im).text((0, 0), "LispBSD boot", font=f, fill=1)
for y in range(H): print(''.join('#' if im.getpixel((x, y)) else ' ' for x in range(W * 12)))
